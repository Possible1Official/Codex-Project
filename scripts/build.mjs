import { mkdir, readFile, writeFile, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('..', import.meta.url));
const files = ['index.html', 'src/app.js', 'src/model.js', 'src/simulation.js', 'src/simulation-ui.js', 'src/workbench.js', 'src/workbench-ui.js', 'src/style.css'];
await mkdir(path.join(root, 'dist/src'), {recursive:true});
for (const file of files) await copyFile(path.join(root, file), path.join(root, 'dist', file));
const {version} = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
await writeFile(path.join(root, 'dist/release.json'), JSON.stringify({name:'Signal Atlas',version,files},null,2)+'\n');
console.log(`Built Signal Atlas ${version}: ${files.length} static files in dist/ (supports subdirectory hosting).`);
